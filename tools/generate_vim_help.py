#!/usr/bin/env python3
"""Embed the UTF-8 support list as VC6-compatible ASCII C source."""
import argparse
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / "docs/vim-help.txt"
target = root / "joe/vimhelp.h"


def generate():
    lines = []
    for line in source.read_text(encoding="utf-8").splitlines(keepends=True):
        escaped = ""
        for byte in line.encode("utf-8"):
            if byte == 10:
                escaped += r"\n"
            elif byte in (34, 92):
                escaped += "\\" + chr(byte)
            elif 32 <= byte < 127:
                escaped += chr(byte)
            else:
                escaped += "\\%03o" % byte
        lines.append('"' + escaped + '"\n')
    return ("/* Generated by tools/generate_vim_help.py from docs/vim-help.txt. */\n"
            "static const char vim_help_text[] =\n" + "".join(lines) + ";\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not target.exists() or target.read_text(encoding="ascii") != content:
            raise SystemExit("Help header is stale; run python3 tools/generate_vim_help.py")
    else:
        target.write_text(content, encoding="ascii")
